const preset = (id: string, label: string, nums: number[], pos: number, edge?: "empty" | "one" | "worst") => {
  const loop = pos >= 0 && pos < nums.length;
  return { id, label, input: { nums, pos }, expect: null, expectByRun: { copy: [...nums].reverse(), seen: loop, floyd: loop, reverse: [...nums].reverse() }, ...(edge ? { edge } : {}) };
};
const tagAt = (f: Frame, name: string) => (f.structs.list as Extract<Frame["structs"][string], { kind: "list" }>).tags.find((t) => t.name === name)?.at;

